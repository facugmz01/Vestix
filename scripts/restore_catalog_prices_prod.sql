-- 2. Actualizar todas las variantes presentes en el backup de UltimatePOS
UPDATE catalog."ProductVariant" v
SET
  "costPrice" = bp.cost_price,
  "basePrice" = bp.sell_price
FROM temp_backup_prices bp
WHERE UPPER(v.sku) = bp.sku;

-- 3. Regla Madre: El costo real de una orden de compra siempre prevalece
--    Se sincroniza el costPrice con el unitCost de la última Orden de Compra registrada
WITH latest_po_costs AS (
  SELECT DISTINCT ON (poli."variantId")
    poli."variantId",
    poli."unitCost"
  FROM purchasing."POLineItem" poli
  JOIN purchasing."PurchaseOrder" po ON po.id = poli."purchaseOrderId"
  ORDER BY poli."variantId", po."createdAt" DESC
)
UPDATE catalog."ProductVariant" v
SET "costPrice" = lpc."unitCost"
FROM latest_po_costs lpc
WHERE v.id = lpc."variantId";

-- 4. Variantes unitarias creadas manualmente (sin OC propia o clonadas)
-- SKU0015-XXL: alinear costo con sus variantes hermanas de la misma compra (19000)
UPDATE catalog."ProductVariant"
SET "costPrice" = 19000, "basePrice" = 19000
WHERE UPPER(sku) = 'SKU0015-XXL';

-- SKU0010-COPY: restaurar devaluación (-2.25%)
UPDATE catalog."ProductVariant"
SET "costPrice" = 39000, "basePrice" = 39000
WHERE UPPER(sku) = 'SKU0010-COPY';

-- Productos Kimchi (creados en Vestix con OC directa)
-- Asegurar que basePrice no quede distorsionado
UPDATE catalog."ProductVariant" v
SET "basePrice" = v."costPrice"
FROM catalog."Product" p
WHERE v."productId" = p.id
  AND p."brandId" = '1ed1b5d7-ba1c-4a93-affd-917b524e7eb8'
  AND v."basePrice" < v."costPrice";

-- 5. Sincronizar el costo del producto padre (catalog."Product"."costPrice")
--    con la primera variante activa
UPDATE catalog."Product" p
SET "costPrice" = sub."costPrice"
FROM (
  SELECT DISTINCT ON ("productId")
    "productId", "costPrice"
  FROM catalog."ProductVariant"
  WHERE "isActive" = true
  ORDER BY "productId", "createdAt" ASC
) sub
WHERE p.id = sub."productId";

